class TempDirTest(unittest.TestCase):
    """Gives each test a temporary directory and silences the script's log."""

    def setUp(self) -> None:
        self.tmp = Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.enterContext(mock.patch.object(bootstrap, "log"))

    def patch(self, **attributes: object) -> None:
        self.enterContext(mock.patch.multiple(bootstrap, **attributes))

    def patch_env(self, **variables: str) -> None:
        self.enterContext(mock.patch.dict(os.environ, variables))

    def patch_token_dir(self) -> Path:
        token_dir = self.tmp / "tokens"
        self.patch(
            TOKEN_DIR=token_dir,
            TOKEN_STAMP=token_dir / "_stamp",
            TOKEN_LOCK=token_dir / "_lock",
            LOG_FILE=self.tmp / "session-start.log",
        )
        return token_dir


Responder = Callable[[str, dict[str, str]], tuple[int, bytes]]


@contextlib.contextmanager
def local_http_server(respond: Responder) -> Iterator[str]:
    """Serves GET requests through respond(path, lowercased headers) and yields the base URL."""

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self) -> None:
            status, body = respond(self.path, {k.lower(): v for k, v in self.headers.items()})
            self.send_response(status)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, format: str, *args: object) -> None:
            return

    server = HTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        yield f"http://127.0.0.1:{server.server_port}"
    finally:
        server.shutdown()
        server.server_close()


def generate_signing_key(directory: Path) -> tuple[Path, str]:
    """Returns a new private key file and its public key."""
    key = directory / "id_ed25519"
    subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)], check=True)
    return key, key.with_suffix(".pub").read_text().strip()


def signed_script(key: Path, directory: Path, source: str) -> tuple[bytes, bytes]:
    """Returns a bootstrap.py with this source and its signature."""
    directory.mkdir()
    script = directory / "bootstrap.py"
    script.write_text(source)
    subprocess.run(
        ["ssh-keygen", "-q", "-Y", "sign", "-f", str(key), "-n", "claude-env", str(script)],
        check=True,
    )
    return script.read_bytes(), script.with_name("bootstrap.py.sig").read_bytes()
